--- 把 {name} / {hometown} 等占位符替换成当前存档里的真实信息
--- 未识别的占位符会被清空（与 LifeStory 保持一致）
---@param text string|nil
---@param state CareerState|nil
---@return string
local function personalize(text, state)
    if text == nil or text == "" then return "" end
    local name = (state and state.name) or "你"
    local hometown = (state and state.hometown) or "故乡"
    return (text:gsub("{(%w+)}", function(key)
        if key == "name" then return name end
        if key == "hometown" then return hometown end
        return ""
    end))
end

