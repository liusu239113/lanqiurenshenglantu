--- 五项能力平均值（用于 minOverall / maxOverall）
---@param state CareerState
---@return number
local function overallOf(state)
    local attrs = state.attrs or {}
    ---@type number
    local sum = 0
    for i = 1, #Config.ATTRS do
        sum = sum + (attrs[Config.ATTRS[i].key] or 0)
    end
    return sum / #Config.ATTRS
end

--- 当前阶段 id（street / high / ncaa / pro / legend）
---@param state CareerState
---@return string
local function stageIdOf(state)
    local def = Config.STAGES[state.stageIndex or 1]
    return def and def.id or ""
end

--- stage 字段：字符串或字符串数组，命中其一即可
---@param state CareerState
---@param stage string|string[]|nil
---@return boolean
local function passStage(state, stage)
    if stage == nil then return true end
    local id = stageIdOf(state)
    if type(stage) == "table" then
        for i = 1, #stage do
            if stage[i] == id then return true end
        end
        return false
    end
    return id == stage
end

--- 把「字符串或字符串数组」统一成数组
---@param value string|string[]|nil
---@return string[]
local function toList(value)
    if value == nil then return {} end
    if type(value) == "table" then
        ---@cast value string[]
        return value
    end
    return { value }
end

--- path 字段：叙事倾向是否领先（且至少累计过 2 次主线选择）
---@param state CareerState
---@param path string|string[]|nil
---@return boolean
local function passPath(state, path)
    if path == nil then return true end
    local paths = state.storyPaths or {}
    local best = math.max(paths.bond or 0, paths.craft or 0, paths.glory or 0)
    local list = toList(path)
    for i = 1, #list do
        local v = paths[list[i]] or 0
        if v >= 2 and v >= best then return true end
    end
    return false
end

--- needsFlag 字段：字符串或数组，列出的章节都必须已看过
---@param state CareerState
---@param needs string|string[]|nil
---@return boolean
local function passFlags(state, needs)
    if needs == nil then return true end
    local seen = state.seenEvents or {}
    local list = toList(needs)
    for i = 1, #list do
        if not seen[list[i]] then return false end
    end
    return true
end

--- minAttr 字段：{ scoring = 60, defense = 55 } 逐项下限
---@param state CareerState
---@param req table<string, number>|nil
---@return boolean
local function passAttrs(state, req)
    if req == nil then return true end
    local attrs = state.attrs or {}
    for key, min in pairs(req) do
        if (attrs[key] or 0) < min then return false end
    end
    return true
end

--- 单个章节的 when 条件是否满足
---@param state CareerState
---@param ch SideStoryChapter
---@return boolean
local function passWhen(state, ch)
    local w = ch.when
    if w == nil then return true end

    local age = state.age or 0
    if w.minAge and age < w.minAge then return false end
    if w.maxAge and age > w.maxAge then return false end

    local season = state.season or 1
    if w.minSeason and season < w.minSeason then return false end
    if w.maxSeason and season > w.maxSeason then return false end

    if not passStage(state, w.stage) then return false end
    if w.minStageIndex and (state.stageIndex or 1) < w.minStageIndex then return false end
    if w.maxStageIndex and (state.stageIndex or 1) > w.maxStageIndex then return false end
    if w.retired ~= nil and (state.retired and true or false) ~= w.retired then return false end

    local fame = state.fame or 0
    if w.minFame and fame < w.minFame then return false end
    if w.maxFame and fame > w.maxFame then return false end

    local morale = state.morale or 0
    if w.minMorale and morale < w.minMorale then return false end
    if w.maxMorale and morale > w.maxMorale then return false end

    local overall = overallOf(state)
    if w.minOverall and overall < w.minOverall then return false end
    if w.maxOverall and overall > w.maxOverall then return false end

    if w.minMoney and (state.money or 0) < w.minMoney then return false end

    if not passAttrs(state, w.minAttr) then return false end
    if not passPath(state, w.path) then return false end
    if not passFlags(state, w.needsFlag) then return false end
    return true
end

-- ============================================================================
-- 索引：按线归档、按 order 排序、记录前驱章节
-- ============================================================================

---@type table<string, SideStoryChapter>
local byId = {}
---@type table<string, SideStoryChapter[]>
local byLine = {}
---@type table<string, string>
local prevById = {}

for i = 1, #chapters do
    local ch = chapters[i]
    byId[ch.id] = ch
    local list = byLine[ch.line]
    if list == nil then
        list = {}
        byLine[ch.line] = list
    end
    table.insert(list, ch)
end

for _, list in pairs(byLine) do
    table.sort(list, function(a, b) return (a.order or 1) < (b.order or 1) end)
    for i = 2, #list do
        local prev = assert(list[i - 1])
        prevById[list[i].id] = prev.id
    end
end

--- 每条线当前递出的那一章（原始章节表，不做展示包装）
--- 规则：未看过 + 同线内 order 最小 + 前驱已看过 + when 通过
---@param state CareerState
---@return SideStoryChapter[]
local function rawCandidates(state)
    local out = {}
    if not state then return out end
    local seen = state.seenEvents or {}

    for i = 1, #SideStory.LINES do
        ---@type SideStoryChapter[]
        local list = byLine[SideStory.LINES[i].id] or {}
        for j = 1, #list do
            local ch = list[j]
            if not seen[ch.id] then
                local prev = prevById[ch.id]
                if (prev == nil or seen[prev]) and passWhen(state, ch) then
                    table.insert(out, ch)
                end
                -- 这条线只看 order 最小的未读章节，后面的要等它先被看过
                break
            end
        end
    end
    return out
end

--- 把章节包装成 EventSystem 可用的事件表
---@param state CareerState
---@param ch SideStoryChapter
---@return table
local function toEvent(state, ch)
    ---@type table[]
    local options = {}
    for i = 1, #ch.options do
        local opt = ch.options[i]
        options[i] = {
            text = opt.text,
            response = personalize(opt.response, state),
            memory = personalize(opt.memory, state),
            fx = opt.fx or {},
        }
    end
    local body = personalize(ch.body, state)
    if state.storyMemory and state.storyMemory ~= "" then
        body = "前情 · " .. state.storyMemory .. "\n\n" .. body
    end
    return {
        id = ch.id,
        once = true,
        storyChapter = true,
        sideStory = true,
        line = ch.line,
        order = ch.order,
        title = ch.title,
        body = body,
        art = ch.art,
        options = options,
        age = state.age,
    }
end

