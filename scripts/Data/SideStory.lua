--- 返回当前所有可触发的支线章节（已看过的排除；每条线最多一个）
---@param state CareerState
---@return table[]
function SideStory.candidates(state)
    local raw = rawCandidates(state)
    local out = {}
    for i = 1, #raw do
        local ch = raw[i]
        out[i] = {
            id = ch.id,
            line = ch.line,
            order = ch.order,
            title = ch.title,
            art = ch.art,
            body = personalize(ch.body, state),
            when = ch.when,
            options = ch.options,
        }
    end
    return out
end

--- 随机挑一条线的下一章（多条线可触发时先随机选线，再取该线 order 最小的未读章节）
---@param state CareerState
---@return table|nil
function SideStory.pick(state)
    local raw = rawCandidates(state)
    if #raw == 0 then return nil end
    local ch = raw[math.random(1, #raw)]
    if ch == nil then return nil end
    return toEvent(state, ch)
end

--- 按 id 取章节正文（用于回顾），支持直接传章节 id 或候选表
---@param state CareerState
---@param id string|table
---@return string
function SideStory.read(state, id)
    if type(id) == "table" then id = id.id end
    local ch = id and byId[id]
    if not ch then return "" end
    return personalize(ch.body, state)
end

--- 已完成（已看过）的支线章节数
---@param state CareerState
---@return number
function SideStory.count(state)
    if not state then return 0 end
    local seen = state.seenEvents or {}
    local n = 0
    for i = 1, #chapters do
        if seen[chapters[i].id] then n = n + 1 end
    end
    return n
end

--- 关系线显示名
---@param lineId string
---@return string
function SideStory.lineName(lineId)
    for i = 1, #SideStory.LINES do
        if SideStory.LINES[i].id == lineId then return SideStory.LINES[i].name end
    end
    return ""
end

--- 按 id 取原始章节定义（调试 / 工具用）
---@param id string
---@return table|nil
function SideStory.get(id)
    return byId[id]
end

--- 每条线的完成进度，供「支线回顾」页使用
---@param state CareerState
---@return table[]
function SideStory.lineProgress(state)
    local seen = (state and state.seenEvents) or {}
    local out = {}
    for i = 1, #SideStory.LINES do
        local line = SideStory.LINES[i]
        local list = byLine[line.id] or {}
        local done = 0
        for j = 1, #list do
            if seen[list[j].id] then done = done + 1 end
        end
        out[i] = { id = line.id, name = line.name, desc = line.desc, done = done, total = #list }
    end
    return out
end

