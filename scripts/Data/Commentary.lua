--   6. DECISIONS 的 body 用 %s 占位实时比分，由 MatchText 填入比赛推演出的真实
--      比分。写死的比分（"比分 6:5"）会和模拟结果脱节 —— 玩家会看到卡面写着
--      领先、记分牌却是落后。带比分差异判断的措辞（"落后一分"）必须改成中性表述。
