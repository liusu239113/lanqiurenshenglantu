local function personalize(text, state)
    return (text:gsub("{(%w+)}", function(key)
        if key == "name" then return state.name end
        if key == "hometown" then return state.hometown end
        return ""
    end))
end

local function toEvent(chapter, state, id)
    local body = personalize(chapter.body, state)
    if chapter.age == 15 then
        for _, origin in ipairs(Config.ORIGINS) do
            if origin.id == state.originId then
                body = string.format("%s，来自%s。你的起点是【%s】：%s\n\n%s",
                    state.name, state.hometown or "故乡", origin.name, origin.desc, body)
                break
            end
        end
    end
    if state.storyMemory and state.storyMemory ~= "" then
        body = "前情 · " .. state.storyMemory .. "\n\n" .. body
    end
    local options = {}
    for i, opt in ipairs(chapter.options) do
        options[i] = {
            text = opt.text, response = personalize(opt.response, state),
            memory = personalize(opt.memory, state), path = opt.path, fx = opt.fx or {},
        }
    end
    return {
        id = id, once = true, storyChapter = true,
        title = chapter.title, body = body, art = chapter.art, options = options,
        age = chapter.age,
    }
end

function LifeStory.atAge(state)
    for _, chapter in ipairs(chapters) do
        local id = "life_age_" .. chapter.age
        if state.age == chapter.age and not state.seenEvents[id] then
            return toEvent(chapter, state, id)
        end
    end
    return nil
end

function LifeStory.afterRetirement(state)
    if not state.retired then return nil end
    for _, chapter in ipairs(after) do
        if not state.seenEvents[chapter.id] then
            return toEvent(chapter, state, chapter.id)
        end
    end
    return nil
end

function LifeStory.read(state, entry)
    for _, chapter in ipairs(chapters) do
        if entry.id == "life_age_" .. chapter.age then
            return personalize(chapter.body, state)
        end
    end
    for _, chapter in ipairs(after) do
        if entry.id == chapter.id then
            return personalize(chapter.body, state)
        end
    end
    return entry.response or ""
end

function LifeStory.ending(state)
    local paths = state.storyPaths or {}
    local leading = "bond"
    if (paths.craft or 0) > (paths[leading] or 0) then leading = "craft" end
    if (paths.glory or 0) > (paths[leading] or 0) then leading = "glory" end
    local preface
    if leading == "bond" then
        preface = "你习惯把球交给还愿意跑动的人。队友、家人、球场上的孩子，组成了比个人数据更宽广的赛场。"
